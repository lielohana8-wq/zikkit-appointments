export async function POST(req: NextRequest) {
  try {
    const { messages } = await req.json();
    if (!Array.isArray(messages) || messages.length === 0) return NextResponse.json({ error: 'no messages' }, { status: 400 });
    const key = process.env.ANTHROPIC_API_KEY;
    if (!key) return NextResponse.json({ reply: 'העוזר עוד לא חובר (חסר מפתח AI בשרת).' });
    const res = await fetch('https://api.anthropic.com/v1/messages', {
      method: 'POST',
      headers: { 'x-api-key': key, 'anthropic-version': '2023-06-01', 'content-type': 'application/json' },
      body: JSON.stringify({ model: 'claude-sonnet-4-6', max_tokens: 1000, system: SYSTEM, messages: messages.slice(-12) }),
    });
    const data = await res.json();
    const reply = Array.isArray(data.content) ? data.content.map((c: { text?: string }) => c.text || '').join('') : '';
    return NextResponse.json({ reply: reply || 'לא הצלחתי לענות — נסו לנסח שוב 🙂' });
  } catch {
    return NextResponse.json({ reply: 'שגיאה זמנית — נסו שוב' }, { status: 200 });
  }
}
